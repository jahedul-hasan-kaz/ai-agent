"""Knowledge-base document schemas. Columns mirror the backend's `docs` table (ai-agent-management)."""
from datetime import datetime
from typing import Any, Literal, Optional
from uuid import UUID

from pydantic import BaseModel, Field, field_validator, model_validator

# The docs.kind check constraint in the backend.
DocKind = Literal["product", "offer", "compliance", "persona", "faq", "policy"]

MAX_CONTENT_CHARS = 100_000
MAX_TAGS = 100
MAX_TAG_CHARS = 100


def _blank_to_none(v: Any) -> Any:
    """Forms send "" for an empty optional field; that means "not set"."""
    return None if isinstance(v, str) and not v.strip() else v


def _clean_tags(tags: Optional[list[str]]) -> Optional[list[str]]:
    if tags is None:
        return None
    if len(tags) > MAX_TAGS or any(len(t) > MAX_TAG_CHARS for t in tags):
        raise ValueError(f"at most {MAX_TAGS} tags of {MAX_TAG_CHARS} characters")
    return [t.strip() for t in tags if t.strip()]


class DocCreate(BaseModel):
    """Required: tenant_id, kind, content. Everything else is optional."""

    tenant_id: UUID
    kind: DocKind
    content: str = Field(..., min_length=1, max_length=MAX_CONTENT_CHARS)
    tags: Optional[list[str]] = None
    metadata: Optional[dict[str, Any]] = None
    image_path: Optional[str] = None
    cadence_id: Optional[UUID] = None

    _tags = field_validator("tags")(_clean_tags)
    _blank = field_validator("image_path", "cadence_id", mode="before")(_blank_to_none)

    @field_validator("content")
    @classmethod
    def _content_not_blank(cls, v: str) -> str:
        if not v.strip():
            raise ValueError("content cannot be blank")
        return v


class DocUpdate(BaseModel):
    """Only the fields sent are changed. `null` clears tags, metadata, image_path and cadence_id."""

    tenant_id: UUID = Field(..., description="Must own the doc; a doc of another tenant is reported as not found.")
    kind: Optional[DocKind] = None
    content: Optional[str] = Field(None, min_length=1, max_length=MAX_CONTENT_CHARS)
    tags: Optional[list[str]] = None
    metadata: Optional[dict[str, Any]] = None
    image_path: Optional[str] = None
    cadence_id: Optional[UUID] = None

    _tags = field_validator("tags")(_clean_tags)
    _blank = field_validator("image_path", "cadence_id", mode="before")(_blank_to_none)

    @field_validator("content")
    @classmethod
    def _content_not_blank(cls, v: Optional[str]) -> Optional[str]:
        if v is not None and not v.strip():
            raise ValueError("content cannot be blank")
        return v

    @model_validator(mode="after")
    def _required_columns_stay_set(self) -> "DocUpdate":
        for name in ("kind", "content"):
            if name in self.model_fields_set and getattr(self, name) is None:
                raise ValueError(f"{name} cannot be null")
        return self


class Embedded(BaseModel):
    model: str
    dimensions: int
    chars: int = Field(..., description="Length of the text that was embedded.")
    truncated: bool = Field(..., description="The text was longer than the embedding model accepts; its tail is not searchable.")


class DocOut(BaseModel):
    id: UUID
    tenant_id: UUID
    kind: str
    tags: list[str]
    content: str
    metadata: Optional[dict[str, Any]] = None
    image_path: Optional[str] = None
    cadence_id: Optional[UUID] = None
    updated_at: datetime
    embedded: Optional[Embedded] = Field(None, description="Set when the embedding was (re)generated by this call.")


class DocDeleted(BaseModel):
    id: UUID
    deleted: bool = True
