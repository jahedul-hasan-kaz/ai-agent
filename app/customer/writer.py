"""
Stores one exchange of a chat completion in the backend's message log: the
customer's message (inbound, status `received`) and the AI reply (outbound,
status `delivered`), in sms_log or email_log, in one transaction.

Only the text, direction, status and timestamps are new. Everything else is
carried over from the thread's latest message so the rows stay attached to
the same lead, campaign step, template and provider: lead_id, cadence_id,
step_num, template fields, the dealer's number or address, and so on. A thread
with no messages yet falls back to the tenant's SMS number / from address.
created_at_et is generated by Postgres; triggers (notify, opt-out/DNC,
template stats, updated_at) fire as for any other insert.
"""
from dataclasses import dataclass
from typing import Optional
from uuid import UUID

import asyncpg

from app.customer.store import email_variants, phone_variants

# Fields copied from the thread's latest message, as they are.
_SMS_KEEP = (
    "lead_id", "cadence_id", "step_num", "attributed_step", "template_variant", "template_id", "variant_id",
    "is_reengagement", "source_cadence_id", "cnp_provider", "ask_type",
)
_EMAIL_KEEP = ("lead_id", "cadence_id", "template_id", "step_num", "template_variant", "provider")

_SMS_LAST_SQL = """
SELECT * FROM public.sms_log
WHERE tenant_id = $1 AND thread_key = ANY($2::text[])
ORDER BY created_at DESC, id DESC LIMIT 1
"""

_EMAIL_LAST_SQL = """
SELECT * FROM public.email_log m
WHERE m.tenant_id = $1 AND (
    lower(m.email_to) = ANY($2::text[]) OR lower(m.email_from) = ANY($2::text[])
    OR lower(substring(m.email_to from '<([^>]+)>')) = ANY($2::text[])
    OR lower(substring(m.email_from from '<([^>]+)>')) = ANY($2::text[]))
ORDER BY m.created_at DESC LIMIT 1
"""

_TENANT_SQL = "SELECT sms_number, email_from_address, email_from_name FROM public.tenants WHERE id = $1"

# clock_timestamp(), not now(): the reply must sort after the customer's message within one transaction.
_SMS_INSERT = """
INSERT INTO public.sms_log (
    tenant_id, thread_key, direction, phone_from, phone_to, message, status, sent_by,
    created_at, updated_at, received_at, delivered_at, {keep}
) VALUES (
    $1, $2, $3, $4, $5, $6, $7, $8,
    clock_timestamp(), clock_timestamp(), clock_timestamp(),
    CASE WHEN $9 THEN clock_timestamp() END, {params}
) RETURNING id::text
"""

_EMAIL_INSERT = """
INSERT INTO public.email_log (
    tenant_id, direction, email_from, email_to, subject, body_text, in_reply_to_message_id, status, sent_by,
    created_at, updated_at, sent_at, delivered_at, {keep}
) VALUES (
    $1, $2, $3, $4, $5, $6, $7, $8, $9,
    clock_timestamp(), clock_timestamp(),
    CASE WHEN $10 THEN clock_timestamp() END,
    CASE WHEN $10 THEN clock_timestamp() END, {params}
) RETURNING id::text
"""


class StoreError(Exception):
    pass


@dataclass
class Stored:
    channel: str
    inbound_id: str
    outbound_id: Optional[str]  # None when there was no reply to log (<NOOP>)


async def store_exchange(
    pool: asyncpg.Pool,
    tenant_id: UUID,
    sms_key: Optional[str],
    email_key: Optional[str],
    customer_text: str,
    reply_text: str,
    sent_by: Optional[str],
    cnp_provider: Optional[str],
    step_num: Optional[int] = None,
) -> Stored:
    async with pool.acquire() as conn, conn.transaction():
        if sms_key:
            return await _store_sms(conn, tenant_id, sms_key, customer_text, reply_text, sent_by, cnp_provider, step_num)
        return await _store_email(conn, tenant_id, email_key, customer_text, reply_text, sent_by, cnp_provider, step_num)


async def _store_sms(conn, tenant_id, key, customer_text, reply_text, sent_by, cnp_provider, step_num) -> Stored:
    last = await conn.fetchrow(_SMS_LAST_SQL, tenant_id, phone_variants(key))
    if last:
        thread_key = last["thread_key"]
        customer = thread_key
        dealer = last["phone_to"] if last["direction"] == "inbound" else last["phone_from"]
        keep = {k: last[k] for k in _SMS_KEEP}
    else:
        tenant = await conn.fetchrow(_TENANT_SQL, tenant_id)
        if not tenant or not tenant["sms_number"]:
            raise StoreError("no earlier SMS in this thread and the tenant has no sms_number")
        thread_key = customer = key.strip()
        dealer = tenant["sms_number"]
        keep = {k: None for k in _SMS_KEEP}
    if cnp_provider:
        keep["cnp_provider"] = cnp_provider
    if step_num is not None:
        keep["step_num"] = step_num

    sql = _SMS_INSERT.format(keep=", ".join(keep), params=", ".join(f"${i}" for i in range(10, 10 + len(keep))))
    inbound = await conn.fetchval(
        sql, tenant_id, thread_key, "inbound", customer, dealer, customer_text, "received", None, False, *keep.values()
    )
    outbound = await conn.fetchval(
        sql, tenant_id, thread_key, "outbound", dealer, customer, reply_text, "delivered", sent_by, True, *keep.values()
    ) if reply_text else None  # no reply (<NOOP>): only the customer's message is logged
    return Stored("sms", inbound, outbound)


async def _store_email(conn, tenant_id, key, customer_text, reply_text, sent_by, cnp_provider, step_num) -> Stored:
    customer = email_variants(key)[0]
    last = await conn.fetchrow(_EMAIL_LAST_SQL, tenant_id, [customer])
    if last:
        dealer = last["email_to"] if last["direction"] == "inbound" else last["email_from"]
        subject = last["subject"] or ""
        reply_to = last["provider_msg_id"]
        keep = {k: last[k] for k in _EMAIL_KEEP}
    else:
        tenant = await conn.fetchrow(_TENANT_SQL, tenant_id)
        if not tenant or not tenant["email_from_address"]:
            raise StoreError("no earlier email in this thread and the tenant has no email_from_address")
        name = tenant["email_from_name"]
        dealer = f"{name} <{tenant['email_from_address']}>" if name else tenant["email_from_address"]
        subject, reply_to = "", None
        keep = {k: None for k in _EMAIL_KEEP}
    if cnp_provider:
        keep["provider"] = cnp_provider
    if step_num is not None:
        keep["step_num"] = step_num
    subject = subject if not subject or subject.lower().startswith("re:") else f"Re: {subject}"

    sql = _EMAIL_INSERT.format(keep=", ".join(keep), params=", ".join(f"${i}" for i in range(11, 11 + len(keep))))
    inbound = await conn.fetchval(
        sql, tenant_id, "inbound", customer, dealer, subject or None, customer_text, reply_to, "received", None, False,
        *keep.values(),
    )
    outbound = await conn.fetchval(
        sql, tenant_id, "outbound", dealer, customer, subject or None, reply_text, reply_to, "delivered", sent_by, True,
        *keep.values(),
    ) if reply_text else None  # no reply (<NOOP>): only the customer's message is logged
    return Stored("email", inbound, outbound)
