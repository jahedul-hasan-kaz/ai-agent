def _load_env(write_mode: str) -> None:
    """dev.env as the app reads it, with tools.write_mode replaced for this process (the file is not touched)."""
    from dotenv import load_dotenv

    load_dotenv("dev.env")
    load_dotenv(".env", override=False)
    raw = os.environ.get("AI_AGENT_CONFIG", "")
    if not raw.strip():
        sys.exit("AI_AGENT_CONFIG is empty: run from the repo with dev.env present")
    cfg = json.loads(raw)
    cfg.setdefault("tools", {})["write_mode"] = write_mode
    os.environ["AI_AGENT_CONFIG"] = json.dumps(cfg)
    os.environ["ENV"] = os.environ.get("ENV") or "dev"


def _dsn() -> str:
    url = os.environ.get("PG_DB_URL", "").strip()
    return url.replace("postgresql+psycopg2://", "postgresql://", 1).replace("postgresql+asyncpg://", "postgresql://", 1)


async def _connect():
    import asyncpg

    return await asyncpg.connect(_dsn(), statement_cache_size=0)


