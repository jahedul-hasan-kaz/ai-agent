"""
Agent regression: seed test cases into public.agent_regression_tests, then run each row through the real
POST /v1/chat/completions and write back what happened.

    .venv/Scripts/python.exe regression/agent_regression.py seed            # create the table, insert the cases once
    .venv/Scripts/python.exe regression/agent_regression.py seed --reseed   # truncate the table, insert the cases again
    .venv/Scripts/python.exe regression/agent_regression.py run             # run every row, update it
    .venv/Scripts/python.exe regression/agent_regression.py run --agent inventory --pending --ids 3 4

The endpoint runs in this process (the app's own FastAPI app over an in-memory transport), unchanged, so every
database query and log line of one test can be attributed to it: that is where tables_used, function_used and
is_guard_protect come from. Nothing on disk is changed. dev.env's tools.write_mode is overridden to dry_run for
this process only (unless --write-mode live), so tools never page the dealer, opt the lead out or write data.
With store=true (STORE, default) each exchange is written to sms_log like production; a message the database's
opt-out trigger would turn into a real DNC (public.is_optout_message, e.g. "STOP") is sent without store unless
--store-optout. The sms_log ids written are in the JSONL report (`stored`).

Set by `seed` (from regression/cases.py): agent_name, input_message, expected_message, intent_classifier, and who the
test is about: tenant_id, thread_key (SMS) and email (the lead's leads.email). `run` sends each row's own tenant_id,
thread_key as sms_thread_key and email as email_thread_key.

Column meanings (filled by `run`):
  output_message       the reply (choices[0].message.content); "ERROR <status>: ..." when the request failed
  score                0-100: <NOOP> agreement is exact; otherwise gpt-oss:20b grades the reply against
                       expected_message (temperature 0)
  tool_used            tools called, in first-use order (response tools_used)
  tool_category        Escalate_To_Human category / Suppress_Lead suppression_category of the calls made
  tool_urgency         Escalate_To_Human urgency of the calls made
  re_route_agent_name  the agent the turn was re-run on after a <NOOP> (routing.to_agent)
  is_noop              the final reply is <NOOP>: nothing would be sent
  is_declined          the agent answered <NOOP> to a real message (routing outcome rerouted / fallback /
                       silent_confirmed)
  is_guard_protect     a gateway guard changed the outcome: opt-out gate, reply guard (tool call written as text,
                       unbacked hand-off claim re-asked or removed), repeat-decline safety net, <NOOP> fallback page
  intent_classifier    the Intent Classifier output sent as node_data
  select_market_value  the vehicle market value the answering agent could see (value agent only; NULL otherwise)
  combined_message     the customer's text since our last reply, as the gateway combined it (n8n Combine messages)
  tables_used          public tables the request read or wrote
  function_used        public database functions the request called
  latency              the endpoint's latency_ms
"""
